// Copies contract ABIs from the Foundry build into packages/shared, so backend and frontend use exactly what is
// deployed. Run after `forge build` in contracts/:  npm run abi
import { readFileSync, writeFileSync } from 'node:fs'

const out = new URL('../contracts/out/', import.meta.url)
const contracts = {
  paymentRouterAbi: 'PaymentRouter.sol/PaymentRouter.json',
  paymentEscrowAbi: 'PaymentEscrow.sol/PaymentEscrow.json',
  complianceRegistryAbi: 'ComplianceRegistry.sol/ComplianceRegistry.json',
  feeVaultAbi: 'FeeVault.sol/FeeVault.json',
  sanctionsOracleAbi: 'SanctionsOracle.sol/SanctionsOracle.json',
  erc20Abi: 'ERC20.sol/ERC20.json',
  localCctpAbi: 'LocalCCTP.sol/LocalCCTP.json',
}

let ts = '// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit.\n\n'
for (const [name, file] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(new URL(file, out), 'utf8'))
  ts += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const\n\n`
}
writeFileSync(new URL('../packages/shared/src/abi.ts', import.meta.url), ts)
console.log(`wrote packages/shared/src/abi.ts (${Object.keys(contracts).length} ABIs)`)
